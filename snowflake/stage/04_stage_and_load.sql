USE DATABASE SYNAPSE_HEALTH;
USE SCHEMA RAW;

-- ─────────────────────────────────────────────────────────────────────────────
-- STEP 1 – PUT CLINICAL NOTES into @RAW.CLINICAL_STAGE/clinical_notes/
-- ─────────────────────────────────────────────────────────────────────────────
-- Execute these PUT commands from a SnowSQL session or Snowflake worksheet.
-- Replace <LOCAL_BASE_PATH> with the absolute path on your local machine.
--
-- Example (Windows):
--   SET LOCAL_BASE_PATH = 'C:/Users/Asus/OneDrive/Desktop/SynapseCortex AI Patient & Member 360 & Clinical Regulatory Copilot/clinical_docs';

-- Hero 1 – Robert Callahan (Safety Violation)
PUT file://<LOCAL_BASE_PATH>/clinical_notes/hero1_note_ROBERT_CALLAHAN.txt
    @RAW.CLINICAL_STAGE/clinical_notes/
    AUTO_COMPRESS = FALSE
    OVERWRITE     = TRUE;

-- Hero 2 – Linda Moreno (Care Gap)
PUT file://<LOCAL_BASE_PATH>/clinical_notes/hero2_note_LINDA_MORENO.txt
    @RAW.CLINICAL_STAGE/clinical_notes/
    AUTO_COMPRESS = FALSE
    OVERWRITE     = TRUE;

-- Hero 3 – James Whitfield (High Risk) – 3 notes
PUT file://<LOCAL_BASE_PATH>/clinical_notes/hero3_note_JAMES_WHITFIELD_inpatient.txt
    @RAW.CLINICAL_STAGE/clinical_notes/
    AUTO_COMPRESS = FALSE
    OVERWRITE     = TRUE;

PUT file://<LOCAL_BASE_PATH>/clinical_notes/hero3_note_JAMES_WHITFIELD_outpatient.txt
    @RAW.CLINICAL_STAGE/clinical_notes/
    AUTO_COMPRESS = FALSE
    OVERWRITE     = TRUE;

PUT file://<LOCAL_BASE_PATH>/clinical_notes/hero3_note_JAMES_WHITFIELD_ED.txt
    @RAW.CLINICAL_STAGE/clinical_notes/
    AUTO_COMPRESS = FALSE
    OVERWRITE     = TRUE;

-- ─────────────────────────────────────────────────────────────────────────────
-- STEP 2 – PUT FDA PACKAGE INSERT TEXT into @RAW.CLINICAL_STAGE/fda_inserts/
-- ─────────────────────────────────────────────────────────────────────────────

-- Hero 1 – Metformin contraindication in CKD
PUT file://<LOCAL_BASE_PATH>/fda_inserts/fda_insert_METFORMIN.txt
    @RAW.CLINICAL_STAGE/fda_inserts/
    AUTO_COMPRESS = FALSE
    OVERWRITE     = TRUE;

-- Hero 2 – HbA1c monitoring standard (HEDIS / ADA)
PUT file://<LOCAL_BASE_PATH>/fda_inserts/fda_insert_HBA1C_MONITORING_STANDARD.txt
    @RAW.CLINICAL_STAGE/fda_inserts/
    AUTO_COMPRESS = FALSE
    OVERWRITE     = TRUE;

-- Hero 3 – Polypharmacy high-risk profile
PUT file://<LOCAL_BASE_PATH>/fda_inserts/fda_insert_POLYPHARMACY_HIGH_RISK.txt
    @RAW.CLINICAL_STAGE/fda_inserts/
    AUTO_COMPRESS = FALSE
    OVERWRITE     = TRUE;

-- ─────────────────────────────────────────────────────────────────────────────
-- STEP 3 – Verify staged files
-- ─────────────────────────────────────────────────────────────────────────────
-- Refresh directory table to pick up newly PUT files
ALTER STAGE RAW.CLINICAL_STAGE REFRESH;

-- List all staged files
LIST @RAW.CLINICAL_STAGE;

-- Expected output: 8 files
--   clinical_notes/hero1_note_ROBERT_CALLAHAN.txt
--   clinical_notes/hero2_note_LINDA_MORENO.txt
